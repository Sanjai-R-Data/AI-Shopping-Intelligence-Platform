"""
AI-Powered Multilingual Shopping Intelligence Platform
RFC 9457 Problem Details for HTTP APIs (application/problem+json).
Centralized error responses, exception handlers, and security boundary protection.
"""

from datetime import datetime, timezone
from http import HTTPStatus
import logging
from typing import Any
from fastapi import FastAPI, Request, status
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field
from starlette.exceptions import HTTPException as StarletteHTTPException

logger = logging.getLogger(__name__)

PROBLEM_CONTENT_TYPE = "application/problem+json"


class ProblemDetail(BaseModel):
    """
    RFC 9457 Problem Details payload structure.
    Standardized machine-readable error representation.
    """

    type: str = Field(
        default="about:blank",
        description="A URI reference that identifies the problem type.",
    )
    title: str = Field(
        ...,
        description="A short, human-readable summary of the problem type.",
    )
    status: int = Field(
        ...,
        description="The HTTP status code generated by the origin server.",
    )
    detail: Any | None = Field(
        default=None,
        description="A human-readable explanation specific to this occurrence of the problem.",
    )
    instance: str | None = Field(
        default=None,
        description="A URI reference that identifies the specific occurrence of the problem.",
    )
    code: str | None = Field(
        default=None,
        description="Platform-specific error code for client error classification.",
    )
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="ISO-8601 UTC timestamp of error occurrence.",
    )
    invalid_params: list[dict[str, Any]] | None = Field(
        default=None,
        description="List of specific invalid parameter errors for validation failures.",
    )


class ProblemJSONResponse(JSONResponse):
    """
    Custom JSONResponse specifying application/problem+json media type.
    """

    media_type = PROBLEM_CONTENT_TYPE


async def http_exception_handler(
    request: Request, exc: StarletteHTTPException
) -> ProblemJSONResponse:
    """
    Handle standard HTTP exceptions with RFC 9457 payload.
    """
    try:
        title = HTTPStatus(exc.status_code).phrase
    except ValueError:
        title = "HTTP Error"

    detail = (
        exc.detail
        if isinstance(exc.detail, (dict, list))
        else (str(exc.detail) if exc.detail is not None else None)
    )

    problem = ProblemDetail(
        type="about:blank",
        title=title,
        status=exc.status_code,
        detail=detail,
        instance=request.url.path,
    )
    return ProblemJSONResponse(
        status_code=exc.status_code,
        content=problem.model_dump(exclude_none=True),
    )


async def validation_exception_handler(
    request: Request, exc: RequestValidationError
) -> ProblemJSONResponse:
    """
    Handle Pydantic request validation errors with RFC 9457 payload and parameter details.
    """
    invalid_params = []
    for err in exc.errors():
        loc = " -> ".join(str(part) for part in err.get("loc", []))
        invalid_params.append(
            {
                "name": loc,
                "reason": err.get("msg", "Invalid value"),
                "type": err.get("type", "value_error"),
            }
        )

    # Use 422 Unprocessable Content (RFC 9110 / HTTP_422_UNPROCESSABLE_CONTENT)
    status_code = getattr(status, "HTTP_422_UNPROCESSABLE_CONTENT", 422)

    problem = ProblemDetail(
        type="https://api.shoppingsense.ai/errors/validation-error",
        title="Unprocessable Entity",
        status=status_code,
        detail="The request body or parameters failed validation schema checks.",
        instance=request.url.path,
        code="REQUEST_VALIDATION_FAILED",
        invalid_params=invalid_params,
    )
    return ProblemJSONResponse(
        status_code=status_code,
        content=problem.model_dump(exclude_none=True),
    )


async def unhandled_exception_handler(
    request: Request, exc: Exception
) -> ProblemJSONResponse:
    """
    Catch-all handler for unhandled internal exceptions.
    Logs full exception trace server-side but returns sanitized response to client (zero leakage).
    """
    logger.exception("Unhandled server exception at %s: %s", request.url.path, exc)

    problem = ProblemDetail(
        type="about:blank",
        title="Internal Server Error",
        status=status.HTTP_500_INTERNAL_SERVER_ERROR,
        detail="An unexpected internal server error occurred. Please try again later.",
        instance=request.url.path,
        code="INTERNAL_SERVER_ERROR",
    )
    return ProblemJSONResponse(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
        content=problem.model_dump(exclude_none=True),
    )


def register_error_handlers(app: FastAPI) -> None:
    """
    Register all RFC 9457 Problem Details handlers with FastAPI app.
    """
    app.add_exception_handler(StarletteHTTPException, http_exception_handler)
    app.add_exception_handler(RequestValidationError, validation_exception_handler)
    app.add_exception_handler(Exception, unhandled_exception_handler)
